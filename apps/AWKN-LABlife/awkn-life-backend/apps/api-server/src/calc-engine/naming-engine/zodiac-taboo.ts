/**
 * 根据年支获取生肖及其禁忌偏旁
 * @param yearZhi 年柱地支（如 '子', '丑'）
 * @returns 生肖名称和禁忌规则，未知地支返回 null
 */
export function getZodiacTaboo(yearZhi: string): { zodiac: string; rule: ZodiacTabooRule } | null {
  const zodiac = DIZHI_TO_ZODIAC[yearZhi];
  if (!zodiac) return null;
  const rule = ZODIAC_TABOO_RADICALS[zodiac];
  if (!rule) return null;
  return { zodiac, rule };
}

/**
 * 获取单个字的所有构件（偏旁）
 * @param char 待检查的字
 * @returns 构件列表，如果不在分解表中则返回 [char]（仅匹配自身）
 */
function getCharRadicals(char: string): string[] {
  return CHAR_RADICALS[char] || [char];
}

/**
 * 检查单个字是否包含生肖禁忌偏旁
 * @param char 待检查的字
 * @param taboos 禁忌偏旁列表
 * @returns 命中的禁忌偏旁列表（空数组 = 无禁忌）
 */
export function checkCharZodiacTaboo(char: string, taboos: string[]): string[] {
  const radicals = getCharRadicals(char);
  const hits: string[] = [];
  for (const taboo of taboos) {
    // 字本身是禁忌字，或字的构件中包含禁忌偏旁
    if (char === taboo || radicals.includes(taboo)) {
      hits.push(taboo);
    }
  }
  return hits;
}

/**
 * 过滤字符列表，移除含生肖禁忌偏旁的字
 * @param chars 候选字符列表
 * @param taboos 禁忌偏旁列表
 * @returns 过滤后的字符列表
 */
export function filterZodiacTabooChars(chars: string[], taboos: string[]): string[] {
  return chars.filter(char => checkCharZodiacTaboo(char, taboos).length === 0);
}
