const flatDict = new Map<string, string>();
for (const category of Object.values(DIVINATION_DICT)) {
  for (const [zh, en] of Object.entries(category)) {
    flatDict.set(zh, en);
  }
}

export function translateTerm(text: string, lang: string): string {
  if (lang === 'zh-CN' || lang === 'zh') return text;
  return flatDict.get(text) || text;
}

export function translateGanZhi(ganZhi: string, lang: string): string {
  if (lang === 'zh-CN' || lang === 'zh') return ganZhi;
  if (DIVINATION_DICT.ganZhiCombinations[ganZhi]) {
    return DIVINATION_DICT.ganZhiCombinations[ganZhi];
  }
  if (ganZhi.length === 2) {
    const gan = translateTerm(ganZhi[0], lang);
    const zhi = translateTerm(ganZhi[1], lang);
    if (gan !== ganZhi[0] || zhi !== ganZhi[1]) return `${gan}-${zhi}`;
  }
  return ganZhi;
}

export function translateObject<T extends Record<string, any>>(
  obj: T,
  lang: string,
  termFields: string[],
  freeTextFields: string[] = [],
): Record<string, any> {
  if (lang === 'zh-CN' || lang === 'zh') return obj;

  const result: Record<string, any> = { ...obj };

  for (const field of termFields) {
    const val = result[field];
    if (typeof val === 'string') {
      result[field] = translateGanZhi(val, lang);
    } else if (Array.isArray(val)) {
      result[field] = val.map((v: string) => translateGanZhi(v, lang));
    }
  }

  return result;
}
